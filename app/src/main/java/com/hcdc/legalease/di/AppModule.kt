package com.hcdc.legalease.di

import android.content.Context
import com.hcdc.legalease.R
import com.hcdc.legalease.core.domain.di.ApplicationScope
import com.hcdc.legalease.core.domain.di.DefaultDispatcher
import com.hcdc.legalease.core.domain.di.IoDispatcher
import com.hcdc.legalease.core.domain.model.GoogleSignInConfig
import dagger.Module
import dagger.Provides
import dagger.hilt.InstallIn
import dagger.hilt.android.qualifiers.ApplicationContext
import dagger.hilt.components.SingletonComponent
import kotlinx.coroutines.CoroutineDispatcher
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.SupervisorJob
import java.time.Clock
import javax.inject.Singleton

@Module
@InstallIn(SingletonComponent::class)
object AppModule {

    @Provides
    @IoDispatcher
    fun ioDispatcher(): CoroutineDispatcher = Dispatchers.IO

    @Provides
    @DefaultDispatcher
    fun defaultDispatcher(): CoroutineDispatcher = Dispatchers.Default

    @Provides
    @Singleton
    @ApplicationScope
    fun applicationScope(@DefaultDispatcher dispatcher: CoroutineDispatcher): CoroutineScope =
        CoroutineScope(SupervisorJob() + dispatcher)

    @Provides
    fun clock(): Clock = Clock.systemUTC()

    /** Generated by the google-services plugin from the web OAuth client in google-services.json. */
    @Provides
    fun googleSignInConfig(@ApplicationContext context: Context): GoogleSignInConfig =
        GoogleSignInConfig(context.getString(R.string.default_web_client_id))
}
