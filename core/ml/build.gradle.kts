/**
 * Encrypts the model prompts in src/prompts into generated Kotlin, so they never ship as plain
 * assets. Deterministic (key and IVs derive from the content) so the build stays cacheable.
 * Deterrence only: the key ships in the app too (see SECURITY.md).
 */
abstract class SealPromptsTask : DefaultTask() {
    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val promptDir: DirectoryProperty

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun seal() {
        val files = promptDir.get().asFile.listFiles { f -> f.extension == "txt" }.orEmpty().sortedBy { it.name }
        val all = files.joinToString("\u0000") { it.name + "\u0000" + it.readText() }
        val key = sha256("legalease/prompts/key|$all")
        val mask = sha256("legalease/prompts/mask|$all")
        val entries = files.joinToString("\n") { file ->
            val plain = file.readText().trim().toByteArray(Charsets.UTF_8)
            val iv = sha256("iv|${file.name}|${file.readText()}").copyOf(12)
            val cipher = Cipher.getInstance("AES/GCM/NoPadding").apply {
                init(Cipher.ENCRYPT_MODE, SecretKeySpec(key, "AES"), GCMParameterSpec(128, iv))
            }
            val sealed = Base64.getEncoder().encodeToString(iv + cipher.doFinal(plain))
            val name = file.nameWithoutExtension.uppercase()
            "    const val $name = \"$sealed\""
        }
        val masked = key.indices.joinToString(", ") { ((key[it].toInt() xor mask[it].toInt()) and 0xFF).toString() }
        val maskList = mask.joinToString(", ") { (it.toInt() and 0xFF).toString() }
        val out = outputDir.get().asFile.resolve("com/hcdc/legalease/core/ml/llm/SealedPrompts.kt")
        out.parentFile.mkdirs()
        out.writeText(
            """
            |// Generated by :core:ml:sealPrompts from src/prompts. Do not edit.
            |package com.hcdc.legalease.core.ml.llm
            |
            |internal object SealedPrompts {
            |$entries
            |    val A: IntArray = intArrayOf($masked)
            |    val B: IntArray = intArrayOf($maskList)
            |}
            |""".trimMargin()
        )
    }

    private fun sha256(text: String): ByteArray = MessageDigest.getInstance("SHA-256").digest(text.toByteArray())
}

val sealPrompts = tasks.register<SealPromptsTask>("sealPrompts") {
    promptDir.set(layout.projectDirectory.dir("src/prompts"))
    outputDir.set(layout.buildDirectory.dir("generated/sealedPrompts"))
}

androidComponents {
    onVariants { variant ->
        variant.sources.java?.addGeneratedSourceDirectory(sealPrompts, SealPromptsTask::outputDir)
    }
}

